#!/usr/bin/env node
// Render a motion-pro spec with Remotion.
//
// Usage:
//   node render.mjs --spec <motion.json> --project <dir> --out <dir> [options]
//
// Options:
//   --fast          draft render without motion blur (faster)
//   --still <f>     render only frame f as PNG (quick visual check)
//   --frames a-b    render only frames a to b
//   --ae            render only the custom layers, each alone as a PNG sequence with alpha
//                   (input for spec_to_jsx.mjs); skips the main video
//   --no-install    skip npm install (only if node_modules is already complete)
//
// The project folder is created from assets/remotion-template on the first run and keeps the
// user's custom components (src/custom/*.tsx) on later runs. Assets referenced by the spec
// (paths relative to the spec file) are copied into the project's public/ folder.

import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {execFileSync} from 'node:child_process';
import {fileURLToPath, pathToFileURL} from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const skillDir = path.resolve(here, '..');
const templateDir = path.join(skillDir, 'assets', 'remotion-template');
const {validateSpec} = await import(pathToFileURL(path.join(here, 'validate_spec.mjs')).href);

function arg(name, def = undefined) {
  const i = process.argv.indexOf(name);
  if (i < 0) return def;
  const v = process.argv[i + 1];
  return v === undefined || v.startsWith('--') ? true : v;
}

const specPath = arg('--spec');
const projectDir = path.resolve(arg('--project', './projeto'));
const outDir = path.resolve(arg('--out', './saida'));
const fast = process.argv.includes('--fast');
const still = arg('--still');
const frames = arg('--frames');
const ae = process.argv.includes('--ae');
const noInstall = process.argv.includes('--no-install');

if (!specPath || specPath === true) {
  console.error('Uso: node render.mjs --spec motion.json --project ./projeto --out ./saida [--fast] [--still 45] [--frames 0-60] [--ae]');
  process.exit(2);
}

const specFile = path.resolve(specPath);
const specDir = path.dirname(specFile);
const specText = fs.readFileSync(specFile, 'utf8');
const spec = JSON.parse(specText);
const {errors, warnings} = validateSpec(spec, {specDir, fix: true});
for (const w of warnings) console.log('AVISO: ' + w);
if (errors.length) {
  for (const e of errors) console.log('ERRO: ' + e);
  console.log(`\nRender cancelado: ${errors.length} erro(s) na spec.`);
  process.exit(1);
}
// --fix may have filled image/video sizes: save only when something changed
if (JSON.stringify(JSON.parse(specText)) !== JSON.stringify(spec)) fs.writeFileSync(specFile, JSON.stringify(spec, null, 2));

const slug = (spec.meta && spec.meta.slug) || 'motion';
fs.mkdirSync(outDir, {recursive: true});

// 1. project folder
const fresh = !fs.existsSync(path.join(projectDir, 'package.json'));
if (fresh) {
  fs.cpSync(templateDir, projectDir, {recursive: true});
} else {
  // refresh the engine from the skill, keep custom components and node_modules
  for (const rel of ['src/engine', 'src/Root.tsx', 'src/index.ts', 'remotion.config.ts', 'tsconfig.json']) {
    fs.cpSync(path.join(templateDir, rel), path.join(projectDir, rel), {recursive: true});
  }
}
fs.mkdirSync(path.join(projectDir, 'public'), {recursive: true});
fs.mkdirSync(path.join(projectDir, 'src', 'custom'), {recursive: true});
fs.writeFileSync(path.join(projectDir, 'src', 'spec.json'), JSON.stringify(spec, null, 2));

// 2. assets referenced by the spec
const assetPaths = new Set();
for (const l of spec.layers) if (l.src) assetPaths.add(l.src);
for (const f of spec.fonts || []) if (f.file) assetPaths.add(f.file);
for (const rel of assetPaths) {
  const from = path.join(specDir, rel);
  const to = path.join(projectDir, 'public', rel);
  fs.mkdirSync(path.dirname(to), {recursive: true});
  fs.copyFileSync(from, to);
}

// 3. custom components next to the spec (custom/*.tsx) are copied into the project
const customSrc = path.join(specDir, 'custom');
if (fs.existsSync(customSrc)) {
  for (const f of fs.readdirSync(customSrc)) {
    if (f.endsWith('.tsx') || f.endsWith('.ts')) fs.copyFileSync(path.join(customSrc, f), path.join(projectDir, 'src', 'custom', f));
  }
}
const customFiles = fs
  .readdirSync(path.join(projectDir, 'src', 'custom'))
  .filter((f) => f.endsWith('.tsx') && !f.startsWith('index.generated'));
const needed = spec.layers.filter((l) => l.type === 'custom').map((l) => l.component);
for (const name of needed) {
  if (!customFiles.includes(name + '.tsx')) {
    console.log(`ERRO: componente custom "${name}" nao encontrado. Crie custom/${name}.tsx ao lado da spec (export default).`);
    process.exit(1);
  }
}
const customIndex = [
  '// Generated by scripts/render.mjs from the files in src/custom. Do not edit by hand.',
  "import type React from 'react';",
  ...customFiles.map((f) => `import ${path.basename(f, '.tsx')} from './${path.basename(f, '.tsx')}';`),
  '',
  `export const customComponents: Record<string, React.FC<any>> = {${customFiles.map((f) => path.basename(f, '.tsx')).join(', ')}};`,
  '',
].join('\n');
fs.writeFileSync(path.join(projectDir, 'src', 'custom', 'index.generated.ts'), customIndex);

// 4. dependencies
const run = (cmd, args, opts = {}) => execFileSync(cmd, args, {cwd: projectDir, stdio: 'inherit', ...opts});
const fontPkgs = [...new Set((spec.fonts || []).filter((f) => f.pkg).map((f) => '@fontsource/' + f.pkg))];
if (!noInstall) {
  if (!fs.existsSync(path.join(projectDir, 'node_modules', 'remotion'))) {
    console.log('Instalando dependencias do Remotion (cerca de 1 minuto)...');
    run('npm', ['install', '--no-audit', '--no-fund', '--loglevel=error']);
  }
  const missing = fontPkgs.filter((p) => !fs.existsSync(path.join(projectDir, 'node_modules', p)));
  if (missing.length) {
    console.log('Instalando fontes: ' + missing.join(', '));
    run('npm', ['install', '--no-audit', '--no-fund', '--loglevel=error', ...missing.map((p) => p + '@5')]);
  }
}

// 5. fonts.generated.ts
const fontLines = ['// Generated by scripts/render.mjs from spec.fonts. Do not edit by hand.'];
for (const f of spec.fonts || []) {
  if (!f.pkg) continue;
  const css = `${f.weight}${f.italic ? '-italic' : ''}.css`;
  const file = path.join(projectDir, 'node_modules', '@fontsource', f.pkg, css);
  if (!fs.existsSync(file)) {
    const dir = path.join(projectDir, 'node_modules', '@fontsource', f.pkg);
    const avail = fs.existsSync(dir) ? fs.readdirSync(dir).filter((x) => /^\d+(-italic)?\.css$/.test(x)).join(', ') : 'pacote nao instalado';
    console.log(`ERRO: a fonte ${f.family} nao tem o peso ${f.weight}${f.italic ? ' italico' : ''}. Disponiveis: ${avail}`);
    process.exit(1);
  }
  fontLines.push(`import '@fontsource/${f.pkg}/${css}';`);
}
fontLines.push('export {};', '');
fs.writeFileSync(path.join(projectDir, 'src', 'fonts.generated.ts'), fontLines.join('\n'));

// 6. browser + render flags
function findBrowser() {
  if (process.env.MOTION_PRO_BROWSER && fs.existsSync(process.env.MOTION_PRO_BROWSER)) return process.env.MOTION_PRO_BROWSER;
  const base = '/opt/pw-browsers';
  if (!fs.existsSync(base)) return null;
  const dirs = fs.readdirSync(base).filter((d) => d.startsWith('chromium_headless_shell-')).sort().reverse();
  for (const d of dirs) {
    const p = path.join(base, d, 'chrome-linux', 'headless_shell');
    if (fs.existsSync(p)) return p;
  }
  return null;
}
const browser = findBrowser();
const common = [`--concurrency=${Math.max(1, os.cpus().length)}`];
if (browser) common.push(`--browser-executable=${browser}`);
if (spec.layers.some((l) => l.type === 'custom' && l.three)) common.push('--gl=swangle');
const props = fast ? ['--props', JSON.stringify({fast: true})] : [];
const npx = (args) => run('npx', ['remotion', ...args]);

const t0 = Date.now();
if (still !== undefined) {
  const f = Number(still);
  const file = path.join(outDir, `${slug}_quadro${f}.png`);
  npx(['still', 'src/index.ts', 'Main', file, `--frame=${f}`, ...common, ...props]);
  console.log(`\nQuadro salvo: ${file}`);
  process.exit(0);
}

// custom layers as PNG sequences with alpha (for After Effects)
if (ae) {
  const customs = spec.layers.filter((x) => x.type === 'custom');
  if (!customs.length) console.log('Nenhuma camada custom: nada para pre-renderizar.');
  for (const l of customs) {
    const dir = path.join(outDir, 'ae', 'prerender', l.id);
    fs.rmSync(dir, {recursive: true, force: true});
    fs.mkdirSync(dir, {recursive: true});
    const a = l.in ?? 0;
    const b = (l.out ?? spec.comp.duration) - 1;
    console.log(`Pre-render da camada ${l.id} (frames ${a}-${b}) com transparencia...`);
    npx(['render', 'src/index.ts', `Layer-${l.id}`, dir, '--sequence', '--image-format=png', `--frames=${a}-${b}`, ...common, ...props]);
  }
  console.log(`\nPronto em ${((Date.now() - t0) / 1000).toFixed(1)} s.\nPre-render: ${path.join(outDir, 'ae', 'prerender')}`);
  process.exit(0);
}

const mp4 = path.join(outDir, `${slug}.mp4`);
const renderArgs = ['render', 'src/index.ts', 'Main', mp4, '--codec=h264', '--crf=18', '--pixel-format=yuv420p', ...common, ...props];
if (frames && frames !== true) renderArgs.push(`--frames=${frames}`);
console.log(`Renderizando ${spec.comp.width}x${spec.comp.height}, ${spec.comp.fps} fps, ${spec.comp.duration} frames${fast ? ' (rascunho sem motion blur)' : ''}...`);
npx(renderArgs);

// 7. contact sheet for self-review: 8 frames in a 4x2 grid
const total = frames && frames !== true ? Number(String(frames).split('-')[1]) - Number(String(frames).split('-')[0]) + 1 : spec.comp.duration;
const picks = Array.from({length: 8}, (_, i) => Math.round((i * (total - 1)) / 7));
const sheet = path.join(outDir, `${slug}_quadros.png`);
const sel = picks.map((n) => `eq(n\\,${n})`).join('+');
const tileW = spec.comp.width >= spec.comp.height ? 480 : 270;
try {
  execFileSync('ffmpeg', ['-loglevel', 'error', '-y', '-i', mp4, '-vf', `select='${sel}',scale=${tileW}:-2,tile=4x2:padding=6:color=0x222222`, '-frames:v', '1', sheet]);
} catch (e) {
  console.log('AVISO: nao gerei a folha de quadros: ' + e.message);
}

const secs = ((Date.now() - t0) / 1000).toFixed(1);
console.log(`\nPronto em ${secs} s.\nVideo: ${mp4}\nQuadros para revisao: ${sheet}`);
